-- La tabla se crea una sola vez para conservar la auditoria de ejecuciones
-- anteriores cuando este script se vuelve a ejecutar.
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_existe
      FROM user_tables
     WHERE table_name = 'AUDITORIA_TARIFA';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE auditoria_tarifa (
                id_auditoria  NUMBER GENERATED BY DEFAULT AS IDENTITY,
                id_tarifa     NUMBER NOT NULL,
                operacion     VARCHAR2(10) NOT NULL,
                usuario_bd    VARCHAR2(128) NOT NULL,
                fecha_cambio  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                id_habitacion NUMBER NOT NULL,
                id_temporada  NUMBER NOT NULL,
                valor_anterior NUMBER(12,2),
                valor_nuevo    NUMBER(12,2),
                CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria),
                CONSTRAINT ck_auditoria_tarifa_operacion
                    CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE'))
            )
        ]';
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_auditoria_tarifa
FOR INSERT OR UPDATE OR DELETE ON tarifa
COMPOUND TRIGGER

    TYPE t_cambio IS RECORD (
        id_tarifa      auditoria_tarifa.id_tarifa%TYPE,
        operacion      auditoria_tarifa.operacion%TYPE,
        id_habitacion  auditoria_tarifa.id_habitacion%TYPE,
        id_temporada   auditoria_tarifa.id_temporada%TYPE,
        valor_anterior auditoria_tarifa.valor_anterior%TYPE,
        valor_nuevo    auditoria_tarifa.valor_nuevo%TYPE
    );

    TYPE t_cambios IS TABLE OF t_cambio INDEX BY PLS_INTEGER;

    g_cambios      t_cambios;
    g_indice       PLS_INTEGER;
    g_usuario_bd   auditoria_tarifa.usuario_bd%TYPE;
    g_fecha_cambio auditoria_tarifa.fecha_cambio%TYPE;

    BEFORE STATEMENT IS
    BEGIN
        g_indice       := 0;
        g_usuario_bd   := SYS_CONTEXT('USERENV', 'SESSION_USER');
        g_fecha_cambio := SYSTIMESTAMP;
    END BEFORE STATEMENT;

    AFTER EACH ROW IS
    BEGIN
        g_indice := g_indice + 1;

        IF INSERTING THEN
            g_cambios(g_indice).id_tarifa      := :NEW.id_tarifa;
            g_cambios(g_indice).operacion      := 'INSERT';
            g_cambios(g_indice).id_habitacion  := :NEW.id_habitacion;
            g_cambios(g_indice).id_temporada   := :NEW.id_temporada;
            g_cambios(g_indice).valor_anterior := NULL;
            g_cambios(g_indice).valor_nuevo    := :NEW.valor_noche;
        ELSIF UPDATING THEN
            g_cambios(g_indice).id_tarifa      := :NEW.id_tarifa;
            g_cambios(g_indice).operacion      := 'UPDATE';
            g_cambios(g_indice).id_habitacion  := :NEW.id_habitacion;
            g_cambios(g_indice).id_temporada   := :NEW.id_temporada;
            g_cambios(g_indice).valor_anterior := :OLD.valor_noche;
            g_cambios(g_indice).valor_nuevo    := :NEW.valor_noche;
        ELSE
            g_cambios(g_indice).id_tarifa      := :OLD.id_tarifa;
            g_cambios(g_indice).operacion      := 'DELETE';
            g_cambios(g_indice).id_habitacion  := :OLD.id_habitacion;
            g_cambios(g_indice).id_temporada   := :OLD.id_temporada;
            g_cambios(g_indice).valor_anterior := :OLD.valor_noche;
            g_cambios(g_indice).valor_nuevo    := NULL;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        FOR i IN 1 .. g_indice LOOP
            INSERT INTO auditoria_tarifa (
                id_tarifa,
                operacion,
                usuario_bd,
                fecha_cambio,
                id_habitacion,
                id_temporada,
                valor_anterior,
                valor_nuevo
            ) VALUES (
                g_cambios(i).id_tarifa,
                g_cambios(i).operacion,
                g_usuario_bd,
                g_fecha_cambio,
                g_cambios(i).id_habitacion,
                g_cambios(i).id_temporada,
                g_cambios(i).valor_anterior,
                g_cambios(i).valor_nuevo
            );
        END LOOP;
    END AFTER STATEMENT;

END trg_auditoria_tarifa;
/

SHOW ERRORS TRIGGER trg_auditoria_tarifa;
