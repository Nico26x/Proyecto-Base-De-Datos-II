-- =============================================================================
-- PROYECTO INTEGRADOR: TurismoUQ - Entrega 2
-- TABLA liquidacion_mensual y PAQUETE pkg_turismo
-- CONTENIDO DEL PAQUETE:
--   valor_estadia      -> delega en la funcion fn_valor_estadia
--   sp_crear_reserva   -> crea una reserva validada (-20201 a -20204)
--   sp_liquidar_mes    -> liquidacion mensual con cursor parametrizado (-20206)
-- NOTAS:
--   * Los triggers son objetos independientes y no van dentro del paquete.
--   * Los procedimientos no hacen COMMIT; la transaccion es de quien llama.
--   * Liquidacion: habitaciones por check-in en el mes; servicios por
--     fecha_consumo, atribuidos al alojamiento dueno del servicio.
--   * Rango del mes: [primer dia del mes, primer dia del mes siguiente).
--   * Volver a liquidar un mes reemplaza el resultado anterior.
-- =============================================================================

-- La tabla se crea una sola vez para conservar el historial al re-ejecutar.
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_existe
      FROM user_tables
     WHERE table_name = 'LIQUIDACION_MENSUAL';

    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE liquidacion_mensual (
                id_liquidacion        NUMBER GENERATED BY DEFAULT AS IDENTITY,
                id_alojamiento        NUMBER NOT NULL,
                periodo               DATE NOT NULL,
                noches                NUMBER NOT NULL,
                ingreso_habitaciones  NUMBER(14,2) NOT NULL,
                ingreso_servicios     NUMBER(14,2) NOT NULL,
                total                 NUMBER(14,2) NOT NULL,
                fecha_generacion      DATE DEFAULT SYSDATE NOT NULL,
                CONSTRAINT pk_liquidacion_mensual PRIMARY KEY (id_liquidacion),
                CONSTRAINT uk_liquidacion_aloj_periodo UNIQUE (id_alojamiento, periodo),
                CONSTRAINT fk_liquidacion_alojamiento FOREIGN KEY (id_alojamiento)
                    REFERENCES alojamiento(id_alojamiento),
                CONSTRAINT ck_liquidacion_valores CHECK (
                    noches >= 0 AND ingreso_habitaciones >= 0 AND
                    ingreso_servicios >= 0 AND total >= 0
                )
            )
        ]';
    END IF;
END;
/

