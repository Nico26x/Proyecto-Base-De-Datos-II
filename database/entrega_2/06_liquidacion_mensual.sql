CREATE OR REPLACE PACKAGE BODY pkg_turismo AS

    ---------------------------------------------------------------------------
    -- valor_estadia: envoltorio de la funcion de valoracion
    ---------------------------------------------------------------------------
    FUNCTION valor_estadia(
        p_id_habitacion IN NUMBER,
        p_fecha_in      IN DATE,
        p_fecha_out     IN DATE
    ) RETURN NUMBER
    IS
    BEGIN
        RETURN fn_valor_estadia(p_id_habitacion, p_fecha_in, p_fecha_out);
    END valor_estadia;

    ---------------------------------------------------------------------------
    -- sp_crear_reserva
    ---------------------------------------------------------------------------
    PROCEDURE sp_crear_reserva(
        p_id_cliente     IN  cliente.id_cliente%TYPE,
        p_id_habitacion  IN  habitacion.id_habitacion%TYPE,
        p_fecha_in       IN  DATE,
        p_fecha_out      IN  DATE,
        p_num_huespedes  IN  NUMBER,
        p_id_reserva     OUT reserva.id_reserva%TYPE
    )
    IS
        v_fecha_in    DATE;
        v_fecha_out   DATE;
        v_existe      PLS_INTEGER;
        v_capacidad   habitacion.capacidad%TYPE;
        v_conflictos  PLS_INTEGER;
        v_subtotal    NUMBER;
    BEGIN
        IF p_id_cliente IS NULL OR p_id_habitacion IS NULL
           OR p_fecha_in IS NULL OR p_fecha_out IS NULL
           OR p_num_huespedes IS NULL THEN
            RAISE_APPLICATION_ERROR(-20204, 'Todos los parametros son obligatorios.');
        END IF;

        v_fecha_in  := TRUNC(p_fecha_in);
        v_fecha_out := TRUNC(p_fecha_out);

        IF v_fecha_out <= v_fecha_in THEN
            RAISE_APPLICATION_ERROR(
                -20202,
                'La fecha de salida debe ser posterior a la fecha de entrada.'
            );
        END IF;

        SELECT COUNT(*) INTO v_existe
          FROM cliente
         WHERE id_cliente = p_id_cliente;

        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20204, 'El cliente ' || p_id_cliente || ' no existe.');
        END IF;

        BEGIN
            SELECT capacidad INTO v_capacidad
              FROM habitacion
             WHERE id_habitacion = p_id_habitacion;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(
                    -20204,
                    'La habitacion ' || p_id_habitacion || ' no existe.'
                );
        END;

        IF p_num_huespedes < 1 THEN
            RAISE_APPLICATION_ERROR(-20203, 'El numero de huespedes debe ser al menos 1.');
        END IF;

        IF p_num_huespedes > v_capacidad THEN
            RAISE_APPLICATION_ERROR(
                -20203,
                'Capacidad excedida: la habitacion ' || p_id_habitacion ||
                ' admite ' || v_capacidad || ' huespedes y se solicitaron ' ||
                p_num_huespedes || '.'
            );
        END IF;

        SELECT COUNT(*) INTO v_conflictos
          FROM reserva_habitacion rh
          JOIN reserva r
            ON r.id_reserva = rh.id_reserva
         WHERE rh.id_habitacion = p_id_habitacion
           AND r.estado <> 'CANCELADA'
           AND TRUNC(rh.fecha_checkin)  < v_fecha_out
           AND TRUNC(rh.fecha_checkout) > v_fecha_in;

        IF v_conflictos > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20201,
                'La habitacion ' || p_id_habitacion || ' no esta disponible del ' ||
                TO_CHAR(v_fecha_in, 'YYYY-MM-DD') || ' al ' ||
                TO_CHAR(v_fecha_out, 'YYYY-MM-DD') || '.'
            );
        END IF;

        v_subtotal := valor_estadia(p_id_habitacion, v_fecha_in, v_fecha_out);

        INSERT INTO reserva (id_cliente, estado)
        VALUES (p_id_cliente, 'CONFIRMADA')
        RETURNING id_reserva INTO p_id_reserva;

        INSERT INTO reserva_habitacion (
            id_reserva, id_habitacion, fecha_checkin, fecha_checkout, subtotal_calculado
        ) VALUES (
            p_id_reserva, p_id_habitacion, v_fecha_in, v_fecha_out, v_subtotal
        );
    END sp_crear_reserva;

    ---------------------------------------------------------------------------
    -- sp_liquidar_mes
    ---------------------------------------------------------------------------
    PROCEDURE sp_liquidar_mes(
        p_anio               IN  NUMBER,
        p_mes                IN  NUMBER,
        p_total_alojamientos OUT NUMBER
    )
    IS
        v_inicio  DATE;
        v_fin     DATE;

        -- Cursor explicito parametrizado: recibe el rango [inicio, fin) del mes.
        CURSOR c_liquidacion(p_inicio DATE, p_fin DATE) IS
            SELECT a.id_alojamiento,
                   NVL(h.noches, 0)               AS noches,
                   NVL(h.ingreso_habitaciones, 0) AS ingreso_habitaciones,
                   NVL(s.ingreso_servicios, 0)    AS ingreso_servicios
              FROM alojamiento a
              LEFT JOIN (
                    SELECT hab.id_alojamiento,
                           SUM(TRUNC(rh.fecha_checkout) - TRUNC(rh.fecha_checkin)) AS noches,
                           SUM(rh.subtotal_calculado)                              AS ingreso_habitaciones
                      FROM reserva_habitacion rh
                      JOIN reserva r
                        ON r.id_reserva = rh.id_reserva
                      JOIN habitacion hab
                        ON hab.id_habitacion = rh.id_habitacion
                     WHERE r.estado <> 'CANCELADA'
                       AND rh.fecha_checkin >= p_inicio
                       AND rh.fecha_checkin <  p_fin
                     GROUP BY hab.id_alojamiento
                   ) h
                ON h.id_alojamiento = a.id_alojamiento
              LEFT JOIN (
                    SELECT sv.id_alojamiento,
                           SUM(rs.subtotal) AS ingreso_servicios
                      FROM reserva_servicio rs
                      JOIN reserva r
                        ON r.id_reserva = rs.id_reserva
                      JOIN servicio sv
                        ON sv.id_servicio = rs.id_servicio
                     WHERE r.estado <> 'CANCELADA'
                       AND rs.fecha_consumo >= p_inicio
                       AND rs.fecha_consumo <  p_fin
                     GROUP BY sv.id_alojamiento
                   ) s
                ON s.id_alojamiento = a.id_alojamiento
             WHERE h.id_alojamiento IS NOT NULL
                OR s.id_alojamiento IS NOT NULL
             ORDER BY a.id_alojamiento;

        v_fila  c_liquidacion%ROWTYPE;
    BEGIN
        IF p_anio IS NULL OR p_mes IS NULL
           OR p_mes NOT BETWEEN 1 AND 12
           OR p_anio NOT BETWEEN 2000 AND 2100 THEN
            RAISE_APPLICATION_ERROR(
                -20206,
                'Periodo invalido: anio ' || p_anio || ', mes ' || p_mes || '.'
            );
        END IF;

        v_inicio := TO_DATE(p_anio || '-' || LPAD(p_mes, 2, '0') || '-01', 'YYYY-MM-DD');
        v_fin    := ADD_MONTHS(v_inicio, 1);

        -- Re-liquidar un mes reemplaza el resultado anterior.
        DELETE FROM liquidacion_mensual
         WHERE periodo = v_inicio;

        p_total_alojamientos := 0;

        OPEN c_liquidacion(v_inicio, v_fin);
        LOOP
            FETCH c_liquidacion INTO v_fila;
            EXIT WHEN c_liquidacion%NOTFOUND;

            INSERT INTO liquidacion_mensual (
                id_alojamiento, periodo, noches,
                ingreso_habitaciones, ingreso_servicios, total
            ) VALUES (
                v_fila.id_alojamiento, v_inicio, v_fila.noches,
                v_fila.ingreso_habitaciones, v_fila.ingreso_servicios,
                v_fila.ingreso_habitaciones + v_fila.ingreso_servicios
            );

            p_total_alojamientos := p_total_alojamientos + 1;
        END LOOP;
        CLOSE c_liquidacion;
    EXCEPTION
        WHEN OTHERS THEN
            IF c_liquidacion%ISOPEN THEN
                CLOSE c_liquidacion;
            END IF;
            RAISE;
    END sp_liquidar_mes;

END pkg_turismo;
/

